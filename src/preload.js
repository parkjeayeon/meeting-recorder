const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('recorderApi', {
  info: () => ipcRenderer.invoke('app:info'),
  start: (opts) => ipcRenderer.invoke('rec:start', opts),
  chunk: (track, samples) => ipcRenderer.send('rec:chunk', { track, samples }),
  stop: (opts) => ipcRenderer.invoke('rec:stop', opts),
  toggle: (mode) => ipcRenderer.send('rec:toggle', mode),
  pause: (on) => ipcRenderer.send('rec:pause', on),
  cancel: () => ipcRenderer.send('rec:cancel'),
  setSpeakers: (n) => ipcRenderer.send('rec:speakers', n),
  onClock: (cb) => ipcRenderer.on('rec:clock', (_e, c) => cb(c)),
  failed: () => ipcRenderer.send('rec:failed'),
  log: (msg) => ipcRenderer.send('app:log', msg),
  reveal: (p) => ipcRenderer.send('app:reveal', p),
  openRecordings: () => ipcRenderer.send('app:openRecordings'),
  chooseRecordings: () => ipcRenderer.invoke('recordings:choose'),
  resetRecordings: () => ipcRenderer.invoke('recordings:reset'),
  permStatus: () => ipcRenderer.invoke('perm:status'),
  permRequest: (kind) => ipcRenderer.invoke('perm:request', kind),
  permOpenSettings: (kind) => ipcRenderer.send('perm:openSettings', kind),
  fnKeyWarning: () => ipcRenderer.invoke('perm:fnKey'),
  openKeyboardSettings: () => ipcRenderer.send('perm:openKeyboard'),
  onboardingGet: () => ipcRenderer.invoke('onboarding:get'),
  onboardingSet: (patch) => ipcRenderer.invoke('onboarding:set', patch),
  onboardingFnTest: (on) => ipcRenderer.send('onboarding:fnTest', on),
  onOnboardingFn: (cb) => ipcRenderer.on('onboarding:fn', (_e, s) => cb(s)),
  onOnboardingTap: (cb) => ipcRenderer.on('onboarding:tap', () => cb()),
  focusApp: () => ipcRenderer.send('app:focus'),
  appReady: () => ipcRenderer.send('app:ready'),
  onPermChanged: (cb) => ipcRenderer.on('perm:changed', () => cb()),
  onCommand: (cb) => ipcRenderer.on('rec:cmd', (_e, cmd) => cb(cmd)),
  onFnStatus: (cb) => ipcRenderer.on('fn:status', (_e, s) => cb(s)),
  dictSettings: () => ipcRenderer.invoke('dict:settings'),
  dictSaveSettings: (patch) => ipcRenderer.invoke('dict:saveSettings', patch),
  dictDownload: () => ipcRenderer.invoke('dict:download'),
  setupStatus: () => ipcRenderer.invoke('setup:status'),
  setupInstall: (id) => ipcRenderer.invoke('setup:install', id),
  setupRemove: (id) => ipcRenderer.invoke('setup:remove', id),
  onSetup: (cb) => ipcRenderer.on('setup:status', (_e, list) => cb(list)),
  onDictEngine: (cb) => ipcRenderer.on('dict:engine', (_e, s) => cb(s)),
  onDictResult: (cb) => ipcRenderer.on('dict:result', (_e, r) => cb(r)),
  onDictStage: (cb) => ipcRenderer.on('dict:stage', (_e, s) => cb(s)),
  providers: (opts) => ipcRenderer.invoke('dict:providers', opts),
  history: () => ipcRenderer.invoke('history:list'),
  recordingsAccess: () => ipcRenderer.invoke('recordings:access'),
  copy: (text) => ipcRenderer.invoke('clipboard:write', text),
  repaste: (text) => ipcRenderer.invoke('dict:repaste', text),
  makeMinutes: (dir, speakers) => ipcRenderer.invoke('minutes:make', dir, speakers),
  resumeMinutes: (dir) => ipcRenderer.invoke('minutes:resume', dir),
  pickAudio: (paths) => ipcRenderer.invoke('meeting:pick', paths),
  importMeeting: (paths, opts) => ipcRenderer.invoke('meeting:import', paths, opts),
  makeGlossary: (dir) => ipcRenderer.invoke('glossary:make', dir),
  explainTerm: (dir, term) => ipcRenderer.invoke('glossary:explain', dir, term),
  updateTerm: (dir, id, patch) => ipcRenderer.invoke('glossary:update', dir, id, patch),
  // 끌어다 놓은 파일의 경로 (렌더러는 샌드박스라 File.path가 없다)
  filePath: (file) => webUtils.getPathForFile(file),
  renameSpeaker: (dir, from, to) => ipcRenderer.invoke('speaker:rename', dir, from, to),
  tokenStatus: () => ipcRenderer.invoke('tokens:status'),
  saveToken: (kind, value) => ipcRenderer.invoke('tokens:save', kind, value),
  clearToken: (kind) => ipcRenderer.invoke('tokens:clear', kind),
  verifyToken: (kind) => ipcRenderer.invoke('tokens:verify', kind),
  openExternal: (url) => ipcRenderer.send('app:openExternal', url),
  readMinutes: (dir) => ipcRenderer.invoke('minutes:read', dir),
  cleanScript: (dir) => ipcRenderer.invoke('script:clean', dir),
  toggleTodo: (dir, index, done) => ipcRenderer.invoke('minutes:todo', dir, index, done),
  makeReview: (dir) => ipcRenderer.invoke('review:make', dir),
  applyReview: (dir, fixes) => ipcRenderer.invoke('review:apply', dir, fixes),
  setReviewStatus: (dir, ids, status) => ipcRenderer.invoke('review:status', dir, ids, status),
  chatReview: (dir, ids, messages) => ipcRenderer.invoke('review:chat', dir, ids, messages),
  finalizeReview: (dir) => ipcRenderer.invoke('review:finalize', dir),
  trashMeeting: (dir) => ipcRenderer.invoke('meeting:trash', dir),
  deleteDictation: (id) => ipcRenderer.invoke('dict:delete', id),
  onSwipe: (cb) => ipcRenderer.on('nav:swipe', (_e, dir) => cb(dir)),
  onMinutes: (cb) => ipcRenderer.on('minutes:status', (_e, s) => cb(s)),
});
